
import os
import re
from datetime import datetime


def generate_report(topic, analysis, verification_report, all_results):
    """Generate and save the final Markdown research report."""

    os.makedirs("reports", exist_ok=True)

    safe_topic = re.sub(
        r"[^a-zA-Z0-9_-]+",
        "_",
        topic.strip()
    ).strip("_")[:60] or "research"

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")

    filename = f"{safe_topic}_{timestamp}.md"
    filepath = os.path.join("reports", filename)

    # Collect unique research sources
    sources = {}

    for task_data in all_results:
        for result in task_data.get("results", []):
            url = result.get("href", "").strip()

            if not url:
                continue

            title = result.get("title") or "Untitled Source"
            readable = bool(result.get("article_text", "").strip())

            if url not in sources:
                sources[url] = {
                    "title": title,
                    "readable": readable
                }
            elif readable:
                sources[url]["readable"] = True

    readable_count = sum(
        1 for source in sources.values()
        if source["readable"]
    )

    source_lines = []

    for index, (url, source) in enumerate(
        sources.items(), start=1
    ):
        source_lines.append(
            f"{index}. [{source['title']}]({url})"
        )

    source_section = "\n".join(source_lines)

    if not source_section:
        source_section = "No sources were collected."

    # Create final Markdown report
    report = f"""# Autonomous AI Research Report

## Research Topic

{topic}

## Report Information

- Generated: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
- Research tasks completed: {len(all_results)}
- Unique sources collected: {len(sources)}
- Sources with readable content: {readable_count}

---

## 1. Research Analysis

{analysis}

---

## 2. Evidence Verification Report

{verification_report}

---

## 3. Source References

{source_section}

---

## 4. Research Limitations

- Some websites may block automated article extraction.
- PDF sources may not have been fully extracted.
- Sources without readable content cannot provide direct verification evidence.
- AI-generated findings can contain inaccuracies.
- Evidence verification is AI-assisted, not independent fact-checking.
- A listed source does not necessarily mean its claims were verified.

---

*Generated by Autonomous AI Research Agent.*
"""

    with open(filepath, "w", encoding="utf-8") as file:
        file.write(report)

    return filepath
